/**
 * Every string the game shows or announces, in French and English.
 * The same dictionary feeds the Astro pages (rendered at build time) and the
 * in-game HUD (bundled with the client script).
 *
 * `lines` are the speech bubbles. Some are famous public catchphrases, quoted
 * as such; the others are made up in character. See the legal notice.
 */
import type { AchievementId } from '../game/achievements';
import type { CampId, Category, GoalId, PowerKind, UltimateId } from '../game/data/types';

export type Lang = 'fr' | 'en';
export const LANGS: readonly Lang[] = ['fr', 'en'];

export interface FigureText {
  name: string;
  short: string;
  party: string;
  title: string;
  power: string;
  desc: string;
  /** Headliners and guest bosses: what they do when they march against the player. */
  boss?: string;
  lines: string[];
}

export interface GameStrings {
  figures: Record<string, FigureText>;
  extras: Record<string, string>;
  extraLines: Record<string, string[]>;
  /** What each extra does (characters page and "New!" cards). */
  about: Record<string, string>;
  /** Headliners' powers: a name (characters page) and what is said when it is announced and when it lands. */
  powers: Record<PowerKind, { name: string; cast?: string; landed?: string }>;
  /** What the crowd is after each night: its name, one piece of it, the banner at the start, and the word written on each piece. */
  goals: Record<GoalId, { name: string; one: string; banner: string; label: string }>;
  camps: Record<CampId, { name: string; short: string; motto: string }>;
  ultimates: Record<UltimateId, { name: string; desc: string }>;
  levels: Record<number, { name: string; date: string; blurb: string }>;
  /** The four card families. */
  types: Record<Category, string>;
  ui: Record<string, string>;
  announce: Record<string, string>;
  headlines: { win: string[]; lose: string[]; endless: string[] };
  /** Two figures of the same camp side by side answer each other: a line each. */
  duos: { a: string; b: string; lines: [string, string] }[];
  achievements: Record<AchievementId, { name: string; desc: string }>;
}

